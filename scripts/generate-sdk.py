JS_BASE = """// BombayChitra API client. {header}

/** An error answered by the API, with its HTTP status, error code and message. */
export class BombayChitraError extends Error {{
  constructor(status, code, message) {{
    super(`${{status}} ${{code}}: ${{message}}`);
    this.name = 'BombayChitraError';
    this.status = status;
    this.code = code;
    this.apiMessage = message;
  }}
}}

/** Client for a BombayChitra server (https://github.com/AmmaarBakshi/BombayChitra). */
export class BombayChitra {{
  /**
   * @param {{string}} [baseUrl] origin of a BombayChitra server
   * @param {{{{ apiKey?: string, fetch?: typeof fetch }}}} [options]
   */
  constructor(baseUrl = 'http://localhost:8080', options = {{}}) {{
    this.baseUrl = baseUrl.replace(/\\/+$/, '');
    this.apiKey = options.apiKey;
    this.fetch = options.fetch ?? globalThis.fetch.bind(globalThis);
  }}

  /** Calls the API; resolves to parsed JSON, or text for a response that is not JSON. */
  async request(method, path, query = {{}}, body = undefined) {{
    const params = new URLSearchParams();
    for (const [key, value] of Object.entries(query)) {{
      if (value === undefined || value === null) continue;
      params.set(key, Array.isArray(value) ? value.join(',') : String(value));
    }}
    const qs = params.toString();
    const headers = {{ Accept: 'application/json' }};
    if (this.apiKey) headers['X-API-Key'] = this.apiKey;
    if (body !== undefined) headers['Content-Type'] = 'application/json';
    const res = await this.fetch(`${{this.baseUrl}}${{path}}${{qs ? `?${{qs}}` : ''}}`, {{ method, headers, body: body === undefined ? undefined : JSON.stringify(body) }});
    const text = await res.text();
    if (!res.ok) {{
      let code = 'http_error';
      let message = text || res.statusText;
      try {{
        ({{ code, message }} = JSON.parse(text).error);
      }} catch {{
        /* not a JSON error */
      }}
      throw new BombayChitraError(res.status, code, message);
    }}
    return (res.headers.get('Content-Type') ?? '').includes('json') ? JSON.parse(text) : text;
  }}
"""


def js_method(op: Operation) -> str:
    args = [p.name for p in op.positional]
    if op.body:
        args.append("body")
    if op.optional:
        args.append("options = {}")
    path = op.path
    for p in op.positional:
        if p.where == "path":
            path = path.replace("{" + p.name + "}", "${encodeURIComponent(" + p.name + ")}")
    query = [p for p in op.params if p.where == "query"]
    entries = []
    for p in query:
        source = p.name if p.required else f"options.{p.name}" if re.match(r"^[A-Za-z_]\w*$", p.name) else f"options['{p.name}']"
        entries.append(f"{p.name}: {source}" if p.name != source else p.name)
    call = f"this.request('{op.method}', `{path}`"
    if query:
        call += ", { " + ", ".join(entries) + " }"
    if op.body:
        call += ", body" if query else ", {}, body"
    return f"  /** {op.summary} */\n  {op.id}({', '.join(args)}) {{\n    return {call});\n  }}"


# Parameters that take a comma-separated list, which the clients also accept as an array.
LISTS = {"kind", "category", "group", "modes", "minutes", "avoid"}


def ts_type(p: Param) -> str:
    if p.enum:
        base = " | ".join(f"'{e}'" for e in p.enum)
    else:
        base = {"integer": "number", "number": "number", "boolean": "boolean"}.get(p.type, "string")
    return f"{base} | string[]" if p.name in LISTS else base


def ts_key(name: str) -> str:
    return name if re.match(r"^[A-Za-z_]\w*$", name) else repr(name)


def dts_method(op: Operation) -> str:
    args = [f"{p.name}: {ts_type(p)}" for p in op.positional]
    if op.body:
        args.append("body: Record<string, unknown>")
    if op.optional:
        fields = "; ".join(f"{ts_key(p.name)}?: {ts_type(p)}" for p in op.optional)
        args.append(f"options?: {{ {fields} }}")
    return f"  /** {op.summary} */\n  {op.id}({', '.join(args)}): Promise<any>;"


def js_client(ops: list[Operation]) -> str:
    return JS_BASE.format(header=HEADER) + "\n" + "\n\n".join(js_method(op) for op in ops) + "\n}\n"


def dts_client(ops: list[Operation]) -> str:
    head = f"""// BombayChitra API client types. {HEADER}

export declare class BombayChitraError extends Error {{
  status: number;
  code: string;
  apiMessage: string;
}}

export declare class BombayChitra {{
  constructor(baseUrl?: string, options?: {{ apiKey?: string; fetch?: typeof fetch }});
  baseUrl: string;
  request(method: string, path: string, query?: Record<string, unknown>, body?: unknown): Promise<any>;
"""
    return head + "\n" + "\n\n".join(dts_method(op) for op in ops) + "\n}\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the generated clients are out of date")
    args = parser.parse_args()
    ops = operations(yaml.safe_load(SPEC.read_text(encoding="utf-8")))
    outputs = {PYTHON: python_client(ops), JS: js_client(ops), DTS: dts_client(ops)}
    stale = [path for path, text in outputs.items() if not path.exists() or path.read_text(encoding="utf-8") != text]
    if args.check:
        for path in stale:
            print(f"{path.relative_to(ROOT)} is out of date: run python scripts/generate-sdk.py", file=sys.stderr)
        return 1 if stale else 0
    for path in stale:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(outputs[path], encoding="utf-8", newline="\n")
        print(f"wrote {path.relative_to(ROOT)}")
    print(f"{len(ops)} operations")
    return 0


if __name__ == "__main__":
    sys.exit(main())
