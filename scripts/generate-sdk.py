#!/usr/bin/env python3
"""Generates the BombayChitra API clients from api/openapi.yaml.

    python scripts/generate-sdk.py           # write sdk/python/bombaychitra/client.py, sdk/js/index.js and index.d.ts
    python scripts/generate-sdk.py --check   # fail if the committed clients differ from the spec (CI)

Every /api/v1 operation becomes a method named after its operationId (search, list_places / listPlaces…): path and
required query parameters are positional, the others are keyword arguments (Python) or an options object
(JavaScript), and operations with a JSON body take the body. Both clients have no dependencies — urllib in Python,
fetch in JavaScript — send an optional API key, and raise an error carrying the API's status, code and message.
Requires PyYAML.
"""
from __future__ import annotations

import argparse
import keyword
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "api" / "openapi.yaml"
PYTHON = ROOT / "sdk" / "python" / "bombaychitra" / "client.py"
JS = ROOT / "sdk" / "js" / "index.js"
DTS = ROOT / "sdk" / "js" / "index.d.ts"
HEADER = "Generated by scripts/generate-sdk.py from api/openapi.yaml — do not edit."


def snake(name: str) -> str:
    """listPlaces → list_places."""
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def py_name(name: str) -> str:
    """A parameter name usable in Python: from → from_."""
    return name + "_" if keyword.iskeyword(name) else name


def first_sentence(text: str | None) -> str:
    text = " ".join((text or "").split())
    # A sentence ends before a capital (not at "e.g. 19.05").
    match = re.match(r"(.+?[.!?])(?=\s+[A-Z(]|$)", text)
    return (match.group(1) if match else text).replace("`", "")


class Param:
    def __init__(self, raw: dict):
        self.name = raw["name"]
        self.where = raw["in"]
        self.required = bool(raw.get("required")) or self.where == "path"
        self.description = first_sentence(raw.get("description"))
        schema = raw.get("schema") or {}
        self.type = schema.get("type", "string")
        self.enum = schema.get("enum")


class Operation:
    def __init__(self, path: str, method: str, raw: dict, components: dict):
        self.path = path
        self.method = method.upper()
        self.id = raw["operationId"]
        self.summary = first_sentence(raw.get("summary"))
        self.params: list[Param] = []
        for p in raw.get("parameters", []):
            if "$ref" in p:
                p = {**components[p["$ref"].split("/")[-1]], **{k: v for k, v in p.items() if k != "$ref"}}
            self.params.append(Param(p))
        self.body = "requestBody" in raw

    @property
    def positional(self) -> list[Param]:
        return [p for p in self.params if p.required]

    @property
    def optional(self) -> list[Param]:
        return [p for p in self.params if not p.required]


def operations(spec: dict) -> list[Operation]:
    components = spec.get("components", {}).get("parameters", {})
    ops = []
    for path, methods in spec["paths"].items():
        if not path.startswith("/api/v1"):
            continue
        for method, raw in methods.items():
            ops.append(Operation(path, method, raw, components))
    return ops


# ---------------------------------------------------------------- Python

PY_BASE = '''"""BombayChitra API client. {header}"""
from __future__ import annotations

import json
import urllib.error
import urllib.parse
import urllib.request
from typing import Any


class BombayChitraError(Exception):
    """An error answered by the API, with its HTTP status, error code and message."""

    def __init__(self, status: int, code: str, message: str):
        super().__init__(f"{{status}} {{code}}: {{message}}")
        self.status, self.code, self.message = status, code, message


class BombayChitra:
    """Client for a BombayChitra server (https://github.com/AmmaarBakshi/BombayChitra).

    >>> api = BombayChitra("http://localhost:8080")
    >>> api.search("CST", limit=1)["items"][0]["name"]
    'Mumbai CSMT'
    """

    def __init__(self, base_url: str = "http://localhost:8080", api_key: str | None = None, timeout: float = 30):
        self.base_url = base_url.rstrip("/")
        self.api_key = api_key
        self.timeout = timeout

    def request(self, method: str, path: str, query: dict[str, Any] | None = None, body: Any = None) -> Any:
        """Calls the API; returns parsed JSON, or text for a response that is not JSON."""
        params = {{}}
        for key, value in (query or {{}}).items():
            if value is None:
                continue
            if isinstance(value, (list, tuple)):
                value = ",".join(str(v) for v in value)
            elif isinstance(value, bool):
                value = "true" if value else "false"
            params[key] = value
        url = self.base_url + path + ("?" + urllib.parse.urlencode(params) if params else "")
        headers = {{"Accept": "application/json", "User-Agent": "bombaychitra-python"}}
        if self.api_key:
            headers["X-API-Key"] = self.api_key
        data = None
        if body is not None:
            data = json.dumps(body).encode()
            headers["Content-Type"] = "application/json"
        req = urllib.request.Request(url, data=data, headers=headers, method=method)
        try:
            with urllib.request.urlopen(req, timeout=self.timeout) as res:
                text = res.read().decode()
                return json.loads(text) if "json" in res.headers.get("Content-Type", "") else text
        except urllib.error.HTTPError as err:
            raw = err.read().decode(errors="replace")
            try:
                e = json.loads(raw)["error"]
                raise BombayChitraError(err.code, e.get("code", "http_error"), e.get("message", raw)) from None
            except (ValueError, KeyError, TypeError):
                raise BombayChitraError(err.code, "http_error", raw or err.reason) from None
'''


def py_method(op: Operation) -> str:
    args = ["self"] + [py_name(p.name) for p in op.positional]
    if op.body:
        args.append("body: dict")
    if op.optional:
        args.append("*")
        args += [f"{py_name(p.name)}=None" for p in op.optional]
    path = op.path
    for p in op.positional:
        if p.where == "path":
            path = path.replace("{" + p.name + "}", "{" + f"urllib.parse.quote(str({py_name(p.name)}), safe='')" + "}")
    path_expr = f'f"{path}"' if "{" in path else f'"{path}"'
    query = [p for p in op.params if p.where == "query"]
    lines = [f"    def {snake(op.id)}({', '.join(args)}) -> Any:"]
    documented = [p for p in op.params if p.description]
    if documented or op.body:
        lines += [f'        """{op.summary}', ""]
        for p in documented:
            lines.append(f"        {py_name(p.name)}: {p.description}")
        if op.body:
            lines.append("        body: the JSON request body (see the API reference).")
        lines.append('        """')
    else:
        lines.append(f'        """{op.summary}"""')
    query_expr = "{" + ", ".join(f'"{p.name}": {py_name(p.name)}' for p in query) + "}"
    call = f'self.request("{op.method}", {path_expr}'
    if query:
        call += f", {query_expr}"
    if op.body:
        call += ", body=body" if query else ", None, body"
    lines.append(f"        return {call})")
    return "\n".join(lines)


def python_client(ops: list[Operation]) -> str:
    return PY_BASE.format(header=HEADER) + "\n" + "\n\n".join(py_method(op) for op in ops) + "\n"


